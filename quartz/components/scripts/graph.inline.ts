type GraphicsInfo = {
  color: string
  gfx: Graphics
  alpha: number
  active: boolean
}

type NodeData = {
  id: SimpleSlug
  text: string
  tags: string[]
} & SimulationNodeDatum

type SimpleLinkData = {
  source: SimpleSlug
  target: SimpleSlug
}

type LinkData = {
  source: NodeData
  target: NodeData
} & SimulationLinkDatum<NodeData>

type LinkRenderData = GraphicsInfo & {
  simulationData: LinkData
}

type NodeRenderData = GraphicsInfo & {
  simulationData: NodeData
  label: Text
}

const localStorageKey = "graph-visited"
function getVisited(): Set<SimpleSlug> {
  return new Set(JSON.parse(localStorage.getItem(localStorageKey) ?? "[]"))
}

function addToVisited(slug: SimpleSlug) {
  const visited = getVisited()
  visited.add(slug)
  localStorage.setItem(localStorageKey, JSON.stringify([...visited]))
}

type TweenNode = {
  update: (time: number) => void
  stop: () => void
}

async function renderGraph(graph: HTMLElement, fullSlug: FullSlug) {
  const slug = simplifySlug(fullSlug)
  const visited = getVisited()
  removeAllChildren(graph)

  let cfg = JSON.parse(graph.dataset["cfg"]!) as D3Config
  // На главной странице показываем полный граф (как Global Graph). simplifySlug("index") даёт "/"
  const isIndex = slug === "/" || slug === "index" || slug === ""
  const isLocalContainer = graph.classList.contains("graph-container")
  if (isIndex && isLocalContainer) {
    cfg = { ...cfg, depth: -1, scale: 0.9, centerForce: 0.2, focusOnHover: true, enableRadial: true }
  }
  let {
    drag: enableDrag,
    zoom: enableZoom,
    depth,
    scale,
    repelForce,
    centerForce,
    linkDistance,
    fontSize,
    opacityScale,
    removeTags,
    showTags,
    focusOnHover,
    enableRadial,
  } = cfg

  const data: Map<SimpleSlug, ContentDetails> = new Map(
    Object.entries<ContentDetails>(await fetchData).map(([k, v]) => [
      simplifySlug(k as FullSlug),
      v,
    ]),
  )
  const links: SimpleLinkData[] = []
  const tags: SimpleSlug[] = []
  const validLinks = new Set(data.keys())

  const tweens = new Map<string, TweenNode>()
  for (const [source, details] of data.entries()) {
    const outgoing = details.links ?? []

    for (const dest of outgoing) {
      if (validLinks.has(dest)) {
        links.push({ source: source, target: dest })
      }
    }

    if (showTags) {
      const localTags = details.tags
        .filter((tag) => !removeTags.includes(tag))
        .map((tag) => simplifySlug(("tags/" + tag) as FullSlug))

      tags.push(...localTags.filter((tag) => !tags.includes(tag)))

      for (const tag of localTags) {
        links.push({ source: source, target: tag })
      }
    }
  }

  const neighbourhood = new Set<SimpleSlug>()
  const wl: (SimpleSlug | "__SENTINEL")[] = [slug, "__SENTINEL"]
  if (depth >= 0) {
    while (depth >= 0 && wl.length > 0) {
      // compute neighbours
      const cur = wl.shift()!
      if (cur === "__SENTINEL") {
        depth--
        wl.push("__SENTINEL")
      } else {
        neighbourhood.add(cur)
        const outgoing = links.filter((l) => l.source === cur)
        const incoming = links.filter((l) => l.target === cur)
        wl.push(...outgoing.map((l) => l.target), ...incoming.map((l) => l.source))
      }
    }
  } else {
    validLinks.forEach((id) => neighbourhood.add(id))
    if (showTags) tags.forEach((tag) => neighbourhood.add(tag))
  }

  const nodes = [...neighbourhood].map((url) => {
    const text = url.startsWith("tags/") ? "#" + url.substring(5) : (data.get(url)?.title ?? url)
    return {
      id: url,
      text,
      tags: data.get(url)?.tags ?? [],
    }
  })
  const graphData: { nodes: NodeData[]; links: LinkData[] } = {
    nodes,
    links: links
      .filter((l) => neighbourhood.has(l.source) && neighbourhood.has(l.target))
      .map((l) => ({
        source: nodes.find((n) => n.id === l.source)!,
        target: nodes.find((n) => n.id === l.target)!,
      })),
  }

  const width = graph.offsetWidth
  const height = Math.max(graph.offsetHeight, 250)

  // we virtualize the simulation and use pixi to actually render it
  const simulation: Simulation<NodeData, LinkData> = forceSimulation<NodeData>(graphData.nodes)
    .force("charge", forceManyBody().strength(-100 * repelForce))
    .force("center", forceCenter().strength(centerForce))
    .force("link", forceLink(graphData.links).distance(linkDistance))
    .force("collide", forceCollide<NodeData>((n) => nodeRadius(n)).iterations(3))

  const radius = (Math.min(width, height) / 2) * 0.8
  if (enableRadial) simulation.force("radial", forceRadial(radius).strength(0.2))

  // precompute style prop strings as pixi doesn't support css variables
  const cssVars = [
    "--secondary",
    "--tertiary",
    "--gray",
    "--light",
    "--lightgray",
    "--dark",
    "--darkgray",
    "--bodyFont",
  ] as const
  const computedStyleMap = cssVars.reduce(
    (acc, key) => {
      acc[key] = getComputedStyle(document.documentElement).getPropertyValue(key)
      return acc
    },
    {} as Record<(typeof cssVars)[number], string>,
  )

  // calculate color
  const color = (d: NodeData) => {
    const isCurrent = d.id === slug
    if (isCurrent) {
      return computedStyleMap["--secondary"]
    } else if (d.id.startsWith("tags/")) {
      return computedStyleMap["--secondary"]
    } else if (visited.has(d.id)) {
      return computedStyleMap["--tertiary"]
    } else {
      return computedStyleMap["--gray"]
    }
  }

  function nodeRadius(d: NodeData) {
    const numLinks = graphData.links.filter(
      (l) => l.source.id === d.id || l.target.id === d.id,
    ).length
    return 2 + Math.sqrt(numLinks)
  }

  let hoveredNodeId: string | null = null
  let hoveredNeighbours: Set<string> = new Set()
  const linkRenderData: LinkRenderData[] = []
  const nodeRenderData: NodeRenderData[] = []
  function updateHoverInfo(newHoveredId: string | null) {
    hoveredNodeId = newHoveredId

    if (newHoveredId === null) {
      hoveredNeighbours = new Set()
      for (const n of nodeRenderData) {
        n.active = false
      }

      for (const l of linkRenderData) {
        l.active = false
      }
    } else {
      hoveredNeighbours = new Set()
      for (const l of linkRenderData) {
        const linkData = l.simulationData
        if (linkData.source.id === newHoveredId || linkData.target.id === newHoveredId) {
          hoveredNeighbours.add(linkData.source.id)
          hoveredNeighbours.add(linkData.target.id)
        }

        l.active = linkData.source.id === newHoveredId || linkData.target.id === newHoveredId
      }

      for (const n of nodeRenderData) {
        n.active = hoveredNeighbours.has(n.simulationData.id)
      }
    }
  }

  let dragStartTime = 0
  let dragging = false

  function renderLinks() {
    tweens.get("link")?.stop()
    const tweenGroup = new TweenGroup()

    for (const l of linkRenderData) {
      let alpha = 1

      // if we are hovering over a node, we want to highlight the immediate neighbours
      // with full alpha and the rest with default alpha
      if (hoveredNodeId) {
        alpha = l.active ? 1 : 0.2
      }

      l.color = l.active ? computedStyleMap["--gray"] : computedStyleMap["--lightgray"]
      tweenGroup.add(new Tweened<LinkRenderData>(l).to({ alpha }, 200))
    }

    tweenGroup.getAll().forEach((tw) => tw.start())
    tweens.set("link", {
      update: tweenGroup.update.bind(tweenGroup),
      stop() {
        tweenGroup.getAll().forEach((tw) => tw.stop())
      },
    })
  }

  function renderLabels() {
    tweens.get("label")?.stop()
    const tweenGroup = new TweenGroup()

    const defaultScale = 1 / scale
    const activeScale = defaultScale * 1.1
    for (const n of nodeRenderData) {
      const nodeId = n.simulationData.id

      if (hoveredNodeId === nodeId) {
        tweenGroup.add(
          new Tweened<Text>(n.label).to(
            {
              alpha: 1,
              scale: { x: activeScale, y: activeScale },
            },
            100,
          ),
        )
      } else {
        tweenGroup.add(
          new Tweened<Text>(n.label).to(
            {
              alpha: n.label.alpha,
              scale: { x: defaultScale, y: defaultScale },
            },
            100,
          ),
        )
      }
    }

    tweenGroup.getAll().forEach((tw) => tw.start())
    tweens.set("label", {
      update: tweenGroup.update.bind(tweenGroup),
      stop() {
        tweenGroup.getAll().forEach((tw) => tw.stop())
      },
    })
  }

  function renderNodes() {
    tweens.get("hover")?.stop()

    const tweenGroup = new TweenGroup()
    for (const n of nodeRenderData) {
      let alpha = 1

      // if we are hovering over a node, we want to highlight the immediate neighbours
      if (hoveredNodeId !== null && focusOnHover) {
        alpha = n.active ? 1 : 0.2
      }

      tweenGroup.add(new Tweened<Graphics>(n.gfx, tweenGroup).to({ alpha }, 200))
    }

    tweenGroup.getAll().forEach((tw) => tw.start())
    tweens.set("hover", {
      update: tweenGroup.update.bind(tweenGroup),
      stop() {
        tweenGroup.getAll().forEach((tw) => tw.stop())
      },
    })
  }

  function renderPixiFromD3() {
    renderNodes()
    renderLinks()
    renderLabels()
  }

  tweens.forEach((tween) => tween.stop())
  tweens.clear()

  const app = new Application()
  await app.init({
    width,
    height,
    antialias: true,
    autoStart: false,
    autoDensity: true,
    backgroundAlpha: 0,
    preference: "webgpu",
    resolution: window.devicePixelRatio,
    eventMode: "static",
  })
  graph.appendChild(app.canvas)

  const stage = app.stage
  stage.interactive = false

  const labelsContainer = new Container<Text>({ zIndex: 3, isRenderGroup: true })
  const nodesContainer = new Container<Graphics>({ zIndex: 2, isRenderGroup: true })
  const linkContainer = new Container<Graphics>({ zIndex: 1, isRenderGroup: true })
  stage.addChild(nodesContainer, labelsContainer, linkContainer)

  for (const n of graphData.nodes) {
    const nodeId = n.id

    const label = new Text({
      interactive: false,
      eventMode: "none",
      text: n.text,
      alpha: 0,
      anchor: { x: 0.5, y: 1.2 },
      style: {
        fontSize: fontSize * 15,
        fill: computedStyleMap["--dark"],
        fontFamily: computedStyleMap["--bodyFont"],
      },
      resolution: window.devicePixelRatio * 4,
    })
    label.scale.set(1 / scale)

    let oldLabelOpacity = 0
    const isTagNode = nodeId.startsWith("tags/")
    const gfx = new Graphics({
      interactive: true,
      label: nodeId,
      eventMode: "static",
      hitArea: new Circle(0, 0, nodeRadius(n)),
      cursor: "pointer",
    })
      .circle(0, 0, nodeRadius(n))
      .fill({ color: isTagNode ? computedStyleMap["--secondary"] : color(n) })
      .on("pointerover", (e) => {
        updateHoverInfo(e.target.label)
        oldLabelOpacity = label.alpha
        if (!dragging) {
          renderPixiFromD3()
        }
      })
      .on("pointerleave", () => {
        updateHoverInfo(null)
        label.alpha = oldLabelOpacity
        if (!dragging) {
          renderPixiFromD3()
        }
      })

    if (isTagNode) {
      gfx.stroke({ width: 2, color: computedStyleMap["--secondary"] })
    }

    nodesContainer.addChild(gfx)
    labelsContainer.addChild(label)

    const nodeRenderDatum: NodeRenderData = {
      simulationData: n,
      gfx,
      label,
      color: color(n),
      alpha: 1,
      active: false,
    }

    nodeRenderData.push(nodeRenderDatum)
  }

  for (const l of graphData.links) {
    const gfx = new Graphics({ interactive: false, eventMode: "none" })
    linkContainer.addChild(gfx)

    const linkRenderDatum: LinkRenderData = {
      simulationData: l,
      gfx,
      color: computedStyleMap["--lightgray"],
      alpha: 1,
      active: false,
    }

    linkRenderData.push(linkRenderDatum)
  }

  let currentTransform = zoomIdentity
  if (enableDrag) {
    select<HTMLCanvasElement, NodeData | undefined>(app.canvas).call(
      drag<HTMLCanvasElement, NodeData | undefined>()
        .container(() => app.canvas)
        .subject(() => graphData.nodes.find((n) => n.id === hoveredNodeId))
        .on("start", function dragstarted(event) {
          if (!event.active) simulation.alphaTarget(1).restart()
          event.subject.fx = event.subject.x
          event.subject.fy = event.subject.y
          event.subject.__initialDragPos = {
            x: event.subject.x,
            y: event.subject.y,
            fx: event.subject.fx,
            fy: event.subject.fy,
          }
          dragStartTime = Date.now()
          dragging = true
        })
        .on("drag", function dragged(event) {
          const initPos = event.subject.__initialDragPos
          event.subject.fx = initPos.x + (event.x - initPos.x) / currentTransform.k
          event.subject.fy = initPos.y + (event.y - initPos.y) / currentTransform.k
        })
        .on("end", function dragended(event) {
          if (!event.active) simulation.alphaTarget(0)
          event.subject.fx = null
          event.subject.fy = null
          dragging = false

          // if the time between mousedown and mouseup is short, we consider it a click
          if (Date.now() - dragStartTime < 500) {
            const node = graphData.nodes.find((n) => n.id === event.subject.id) as NodeData
            const targ = resolveRelative(fullSlug, node.id)
            showContentModal(new URL(targ, window.location.toString()))
          }
        }),
    )
  } else {
    for (const node of nodeRenderData) {
      node.gfx.on("click", () => {
        const targ = resolveRelative(fullSlug, node.simulationData.id)
        showContentModal(new URL(targ, window.location.toString()))
      })
    }
  }

  if (enableZoom) {
    select<HTMLCanvasElement, NodeData>(app.canvas).call(
      zoom<HTMLCanvasElement, NodeData>()
        .extent([
          [0, 0],
          [width, height],
        ])
        .scaleExtent([0.25, 4])
        .on("zoom", ({ transform }) => {
          currentTransform = transform
          stage.scale.set(transform.k, transform.k)
          stage.position.set(transform.x, transform.y)

          // zoom adjusts opacity of labels too
          const scale = transform.k * opacityScale
          let scaleOpacity = Math.max((scale - 1) / 3.75, 0)
          const activeNodes = nodeRenderData.filter((n) => n.active).flatMap((n) => n.label)

          for (const label of labelsContainer.children) {
            if (!activeNodes.includes(label)) {
              label.alpha = scaleOpacity
            }
          }
        }),
    )
  }

  let stopAnimation = false
  function animate(time: number) {
    if (stopAnimation) return
    for (const n of nodeRenderData) {
      const { x, y } = n.simulationData
      if (!x || !y) continue
      n.gfx.position.set(x + width / 2, y + height / 2)
      if (n.label) {
        n.label.position.set(x + width / 2, y + height / 2)
      }
    }

    for (const l of linkRenderData) {
      const linkData = l.simulationData
      l.gfx.clear()
      l.gfx.moveTo(linkData.source.x! + width / 2, linkData.source.y! + height / 2)
      l.gfx
        .lineTo(linkData.target.x! + width / 2, linkData.target.y! + height / 2)
        .stroke({ alpha: l.alpha, width: 0.5, color: l.color })
    }

    tweens.forEach((t) => t.update(time))
    app.renderer.render(stage)
    requestAnimationFrame(animate)
  }

  requestAnimationFrame(animate)
  return () => {
    stopAnimation = true
    app.destroy()
  }
}

let localGraphCleanups: (() => void)[] = []
let globalGraphCleanups: (() => void)[] = []

function cleanupLocalGraphs() {
  for (const cleanup of localGraphCleanups) {
    cleanup()
  }
  localGraphCleanups = []
}

function cleanupGlobalGraphs() {
  for (const cleanup of globalGraphCleanups) {
    cleanup()
  }
  globalGraphCleanups = []
}

document.addEventListener("nav", async (e: CustomEventMap["nav"]) => {
  const slug = e.detail.url
  addToVisited(simplifySlug(slug))

  async function renderLocalGraph() {
    cleanupLocalGraphs()
    const localGraphContainers = document.getElementsByClassName("graph-container")
    for (const container of localGraphContainers) {
      localGraphCleanups.push(await renderGraph(container as HTMLElement, slug))
    }
  }

  await renderLocalGraph()
  const handleThemeChange = () => {
    void renderLocalGraph()
  }

  document.addEventListener("themechange", handleThemeChange)
  window.addCleanup(() => {
    document.removeEventListener("themechange", handleThemeChange)
  })

  const containers = [...document.getElementsByClassName("global-graph-outer")] as HTMLElement[]
  async function renderGlobalGraph() {
    const slug = getFullSlug(window)
    for (const container of containers) {
      container.classList.add("active")
      const sidebar = container.closest(".sidebar") as HTMLElement
      if (sidebar) {
        sidebar.style.zIndex = "1"
      }

      const wrapper = container.querySelector(".global-graph-wrapper") as HTMLElement
      const graphContainer = container.querySelector(".global-graph-container") as HTMLElement
      const dragHandle = container.querySelector(".global-graph-drag-handle") as HTMLElement
      const closeBtn = container.querySelector(".global-graph-close") as HTMLButtonElement

      registerEscapeHandler(container, hideGlobalGraph)
      closeBtn?.addEventListener("click", hideGlobalGraph)

      if (wrapper) {
        const MIN_W = 300
        const MIN_H = 200
        const setWrapperPos = (x: number, y: number) => {
          wrapper.style.left = `calc(50% + ${x}px)`
          wrapper.style.top = `calc(50% + ${y}px)`
        }
        const setupGlobalResize = (corner: "se" | "sw" | "ne" | "nw") => {
          const handle = container.querySelector(`.graph-window-resize-${corner}`) as HTMLElement
          if (!handle) return
          function startResize(clientX: number, clientY: number) {
            const rect = wrapper.getBoundingClientRect()
            const sw = rect.width
            const sh = rect.height
            const sx = clientX
            const sy = clientY
            const startPosX = rect.left + rect.width / 2 - window.innerWidth / 2
            const startPosY = rect.top + rect.height / 2 - window.innerHeight / 2

            function update(cx: number, cy: number) {
              let w: number
              let h: number
              let dX = 0
              let dY = 0
              if (corner === "se") {
                w = Math.max(MIN_W, sw + cx - sx)
                h = Math.max(MIN_H, sh + cy - sy)
              } else if (corner === "sw") {
                w = Math.max(MIN_W, sw + sx - cx)
                h = Math.max(MIN_H, sh + cy - sy)
                dX = -(w - sw) / 2
              } else if (corner === "ne") {
                w = Math.max(MIN_W, sw + cx - sx)
                h = Math.max(MIN_H, sh + sy - cy)
                dY = -(h - sh) / 2
              } else {
                w = Math.max(MIN_W, sw + sx - cx)
                h = Math.max(MIN_H, sh + sy - cy)
                dX = -(w - sw) / 2
                dY = -(h - sh) / 2
              }
              wrapper.style.width = `${w}px`
              wrapper.style.height = `${h}px`
              setWrapperPos(startPosX + dX, startPosY + dY)
            }
            const endResize = () => {
              document.removeEventListener("mousemove", onMouseMove)
              document.removeEventListener("mouseup", endResize)
              document.removeEventListener("pointerup", onPointerUp)
              document.removeEventListener("pointercancel", onPointerUp)
              document.removeEventListener("touchmove", onTouchMove, { capture: true })
              document.removeEventListener("touchend", onTouchEnd)
              document.body.style.userSelect = ""
            }
            const onMouseMove = (ev: MouseEvent) => update(ev.clientX, ev.clientY)
            const onPointerUp = () => endResize()
            const onTouchMove = (ev: TouchEvent) => {
              if (ev.touches.length > 0) {
                ev.preventDefault()
                update(ev.touches[0].clientX, ev.touches[0].clientY)
              }
            }
            const onTouchEnd = () => endResize()
            document.body.style.userSelect = "none"
            document.addEventListener("mousemove", onMouseMove)
            document.addEventListener("mouseup", endResize)
            document.addEventListener("pointerup", onPointerUp)
            document.addEventListener("pointercancel", onPointerUp)
            document.addEventListener("touchmove", onTouchMove, { passive: false, capture: true })
            document.addEventListener("touchend", onTouchEnd)
          }
          handle.onmousedown = (e: MouseEvent) => {
            e.preventDefault()
            const pid = (e as unknown as PointerEvent).pointerId
            startResize(e.clientX, e.clientY)
            if (pid !== undefined && handle.setPointerCapture) {
              handle.setPointerCapture(pid)
            }
          }
          handle.ontouchstart = (e: TouchEvent) => {
            if (e.touches.length > 0) {
              e.preventDefault()
              const t = e.touches[0]
              startResize(t.clientX, t.clientY)
              if (handle.setPointerCapture) {
                handle.setPointerCapture(t.identifier)
              }
            }
          }
          globalGraphCleanups.push(() => {
            handle.onmousedown = null
            handle.ontouchstart = null
          })
        }
        ;(["se", "sw", "ne", "nw"] as const).forEach(setupGlobalResize)
      }

      if (wrapper && dragHandle) {
        wrapper.style.left = ""
        wrapper.style.top = ""
        wrapper.style.width = ""
        wrapper.style.height = ""

        let posX = 0,
          posY = 0
        let dragStartX = 0,
          dragStartY = 0,
          innerStartX = 0,
          innerStartY = 0

        function initPosition() {
          const rect = wrapper.getBoundingClientRect()
          posX = rect.left + rect.width / 2 - window.innerWidth / 2
          posY = rect.top + rect.height / 2 - window.innerHeight / 2
        }

        function startGlobalDrag(clientX: number, clientY: number) {
          initPosition()
          dragStartX = clientX
          dragStartY = clientY
          innerStartX = posX
          innerStartY = posY

          function onMove(cx: number, cy: number) {
            posX = innerStartX + cx - dragStartX
            posY = innerStartY + cy - dragStartY
            wrapper.style.left = `calc(50% + ${posX}px)`
            wrapper.style.top = `calc(50% + ${posY}px)`
          }
          function onEnd() {
            document.removeEventListener("mousemove", onMouseMove)
            document.removeEventListener("mouseup", onEnd)
            document.removeEventListener("pointerup", onPointerUp)
            document.removeEventListener("pointercancel", onPointerUp)
            document.removeEventListener("touchmove", onTouchMove, { capture: true })
            document.removeEventListener("touchend", onTouchEnd)
            document.body.style.userSelect = ""
          }
          const onMouseMove = (e: MouseEvent) => onMove(e.clientX, e.clientY)
          const onPointerUp = () => onEnd()
          const onTouchMove = (e: TouchEvent) => {
            if (e.touches.length > 0) {
              e.preventDefault()
              onMove(e.touches[0].clientX, e.touches[0].clientY)
            }
          }
          const onTouchEnd = () => onEnd()
          document.body.style.userSelect = "none"
          document.addEventListener("mousemove", onMouseMove)
          document.addEventListener("mouseup", onEnd)
          document.addEventListener("pointerup", onPointerUp)
          document.addEventListener("pointercancel", onPointerUp)
          document.addEventListener("touchmove", onTouchMove, { passive: false, capture: true })
          document.addEventListener("touchend", onTouchEnd)
        }

        dragHandle.onmousedown = (e: MouseEvent) => {
          if ((e.target as HTMLElement).closest("button")) return
          e.preventDefault()
          const pid = (e as unknown as PointerEvent).pointerId
          startGlobalDrag(e.clientX, e.clientY)
          if (pid !== undefined && dragHandle.setPointerCapture) {
            dragHandle.setPointerCapture(pid)
          }
        }
        dragHandle.ontouchstart = (e: TouchEvent) => {
          if ((e.target as HTMLElement).closest("button")) return
          if (e.touches.length > 0) {
            e.preventDefault()
            const t = e.touches[0]
            startGlobalDrag(t.clientX, t.clientY)
            if (dragHandle.setPointerCapture) {
              dragHandle.setPointerCapture(t.identifier)
            }
          }
        }

        globalGraphCleanups.push(() => {
          closeBtn?.removeEventListener("click", hideGlobalGraph)
          dragHandle.onmousedown = null
          dragHandle.ontouchstart = null
        })
      }

      if (graphContainer) {
        globalGraphCleanups.push(await renderGraph(graphContainer, slug))
      }
    }
  }

  function hideGlobalGraph() {
    cleanupGlobalGraphs()
    for (const container of containers) {
      container.classList.remove("active")
      const sidebar = container.closest(".sidebar") as HTMLElement
      if (sidebar) {
        sidebar.style.zIndex = ""
      }
    }
  }

  async function shortcutHandler(e: HTMLElementEventMap["keydown"]) {
    if (e.key === "g" && (e.ctrlKey || e.metaKey) && !e.shiftKey) {
      e.preventDefault()
      const anyGlobalGraphOpen = containers.some((container) =>
        container.classList.contains("active"),
      )
      anyGlobalGraphOpen ? hideGlobalGraph() : renderGlobalGraph()
    }
  }

  const containerIcons = document.getElementsByClassName("global-graph-icon")
  Array.from(containerIcons).forEach((icon) => {
    icon.addEventListener("click", renderGlobalGraph)
    window.addCleanup(() => icon.removeEventListener("click", renderGlobalGraph))
  })

  document.addEventListener("keydown", shortcutHandler)
  window.addCleanup(() => {
    document.removeEventListener("keydown", shortcutHandler)
    cleanupLocalGraphs()
    cleanupGlobalGraphs()
  })
})
